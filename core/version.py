"""项目版本号管理。

集中定义版本号，供 GUI 显示与打包时写入 exe 文件属性使用。
版本号遵循语义化版本：主版本.次版本.修订号
"""

# 版本号字符串：GUI 标题、关于对话框、日志均引用此常量
# 修改版本号只需改这一处
VERSION = "1.0.0"

# 版本号四元组（Windows 文件版本信息要求 4 段）
# 自动从 VERSION 扩展，不足 4 段补 0
VERSION_TUPLE = tuple(int(x) for x in (VERSION.split(".") + ["0", "0", "0", "0"])[:4])
